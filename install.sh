#!/bin/sh
# =============================================================================
# AZURON — One-shot install script
# Works on: Termux/Android (ARM64) + Linux (x86_64 / ARM64)
# Usage:
#   git clone https://github.com/ShaikhZaid404/azuron.git
#   cd azuron
#   sh install.sh
# =============================================================================

set -e

REPO_DIR="$(cd "$(dirname "$0")" && pwd)"
AZURON_HOME="${AZURON_HOME:-$HOME/.azuron}"

# ---- Colour helpers (silent if no tty) ----------------------------------------
_bold=""  _reset=""  _green=""  _cyan=""  _yellow=""  _red=""
if [ -t 1 ]; then
  _bold="\033[1m"  _reset="\033[0m"  _green="\033[32m"
  _cyan="\033[36m"  _yellow="\033[33m"  _red="\033[31m"
fi

log()  { printf "${_cyan}[AZURON]${_reset} %s\n" "$1"; }
ok()   { printf "${_green}[CHECK]${_reset}  %s\n" "$1"; }
warn() { printf "${_yellow}[WARN]${_reset}   %s\n" "$1"; }
err()  { printf "${_red}[ERROR]${_reset}  %s\n" "$1"; exit 1; }

# ---- Detect Termux vs standard Linux ------------------------------------------
IS_TERMUX=0
if [ -n "$PREFIX" ] && [ -d "$PREFIX/bin" ]; then
  IS_TERMUX=1
fi

if [ "$IS_TERMUX" = "1" ]; then
  BIN_DIR="$PREFIX/bin"
  NODE_BIN="$PREFIX/bin/node"
else
  # Prefer ~/.local/bin (user-writable, no sudo needed)
  BIN_DIR="$HOME/.local/bin"
  mkdir -p "$BIN_DIR"
  NODE_BIN="$(command -v node 2>/dev/null || true)"
fi

# ---- Pre-flight checks --------------------------------------------------------
log "AZURON Installer starting..."
log "Repo:      $REPO_DIR"
log "Data home: $AZURON_HOME"
log "Bin dir:   $BIN_DIR"

command -v node >/dev/null 2>&1 || err "Node.js >= 22 is required. Install with: pkg install nodejs (Termux) or https://nodejs.org"
NODE_VER="$(node -e 'process.stdout.write(process.version)')"
NODE_MAJOR="$(echo "$NODE_VER" | sed 's/v\([0-9]*\).*/\1/')"
if [ "$NODE_MAJOR" -lt 22 ]; then
  err "Node.js >= 22 required (found $NODE_VER). Run: pkg upgrade nodejs"
fi
ok "Node.js $NODE_VER"

command -v npm >/dev/null 2>&1 || err "npm not found. Install with: pkg install nodejs"
ok "npm found"

# ---- npm install + build -------------------------------------------------------
FORCE_INSTALL=0
if [ "$1" = "--force" ] || [ "$1" = "-f" ]; then
  FORCE_INSTALL=1
fi

cd "$REPO_DIR"

if [ "$FORCE_INSTALL" = "0" ] && [ -d "$REPO_DIR/node_modules" ]; then
  ok "Dependencies already installed (skipping npm install; use --force to reinstall)"
else
  log "Installing npm dependencies..."
  if [ "$IS_TERMUX" = "1" ]; then
    node "$REPO_DIR/node_modules/.bin/npm" install 2>/dev/null || npm install
  else
    npm install
  fi
  ok "Dependencies installed"
fi

if [ "$FORCE_INSTALL" = "0" ] && [ -f "$REPO_DIR/packages/cezar/dist/index.js" ] && [ -f "$REPO_DIR/packages/cezar/web/dist/index.html" ]; then
  ok "Build already exists (skipping npm run build; use --force to rebuild)"
else
  log "Building all packages (server + web)..."
  npm run build
  ok "Build complete"
fi

# ---- Create ~/.azuron directory structure -------------------------------------
log "Creating AZURON data directories under $AZURON_HOME ..."
mkdir -p \
  "$AZURON_HOME/chats/global" \
  "$AZURON_HOME/chats/projects" \
  "$AZURON_HOME/profiles/antigravity" \
  "$AZURON_HOME/profiles/codex" \
  "$AZURON_HOME/logs" \
  "$AZURON_HOME/tmp"

# Write default config if not present
if [ ! -f "$AZURON_HOME/config.json" ]; then
  cat > "$AZURON_HOME/config.json" <<EOF
{
  "version": 1,
  "port": 45160,
  "theme": "dark",
  "defaultProvider": "antigravity",
  "installDir": "$REPO_DIR",
  "installedAt": "$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
}
EOF
  ok "Config created at $AZURON_HOME/config.json"
fi

# ---- Create global azuron wrapper in BIN_DIR ----------------------------------
WRAPPER="$BIN_DIR/azuron"

# On Termux /usr/bin/env doesn't resolve properly for scripts on internal storage
# so we write a plain sh wrapper that calls node directly
cat > "$WRAPPER" <<WRAPPER_EOF
#!/bin/sh
# AZURON global launcher — auto-generated by install.sh
AZURON_DIR="$REPO_DIR"
NODE="\${AZURON_NODE_BIN:-$(command -v node)}"
exec "\$NODE" --max-old-space-size=256 "\$AZURON_DIR/bin/azuron" "\$@"
WRAPPER_EOF

chmod +x "$WRAPPER"
ok "Global command installed: $WRAPPER"

# ---- Verify wrapper is on PATH ------------------------------------------------
if ! command -v azuron >/dev/null 2>&1; then
  warn "azuron not on PATH yet."
  if [ "$IS_TERMUX" = "0" ]; then
    warn "Add this to your ~/.bashrc or ~/.zshrc:"
    printf "  export PATH=\"\$HOME/.local/bin:\$PATH\"\n"
  else
    warn "Restart Termux or run: source ~/.bashrc"
  fi
fi

# ---- Final summary ------------------------------------------------------------
printf "\n"
printf "${_bold}+--------------------------------------------------+${_reset}\n"
printf "${_bold}  AZURON installed successfully                     ${_reset}\n"
printf "${_bold}+--------------------------------------------------+${_reset}\n"
printf "\n"
printf "  Data home : %s\n" "$AZURON_HOME"
printf "  Repo      : %s\n" "$REPO_DIR"
printf "  Binary    : %s\n" "$WRAPPER"
printf "\n"
printf "  Commands:\n"
printf "    azuron start        — start server (http://127.0.0.1:45160)\n"
printf "    azuron stop         — stop server\n"
printf "    azuron status       — show running status\n"
printf "    azuron restart      — restart server\n"
printf "    azuron doctor       — environment diagnostic\n"
printf "    azuron storage clean --dry-run  — preview cleanup\n"
printf "\n"
printf "  ${_green}Run: azuron start${_reset}\n"
printf "\n"
